//! Hand-made bitmap fonts: a proportional 5x7 font with lowercase and descenders, and a tiny
//! 3x5 digit font for stack counts.

pub struct Glyph {
    pub w: u8,
    /// Row bitmasks, bit 0 = leftmost column; rows 0..9 (7 = baseline + 1, descenders below).
    pub rows: [u8; 9],
}

pub struct Font {
    glyphs: Vec<(char, Glyph)>,
    ascii: [Option<usize>; 128],
    pub line_h: i32,
    pub space: i32,
}

